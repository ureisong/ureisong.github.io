def get_config_url(name: str) -> str:
    """환경변수를 우선하고, 없으면 정적 config.js에서 URL을 읽습니다."""
    env_value = str(os.environ.get(name, "") or "").strip()
    if env_value:
        return env_value
    try:
        source = CONFIG_PATH.read_text(encoding="utf-8")
    except OSError:
        return ""
    match = re.search(r"(?m)^\s*" + re.escape(name) + r"\s*:\s*([\"'])(.*?)\1\s*,?\s*$", source)
    return str(match.group(2) if match else "").strip()


def parse_csv_text(text: str, source_name: str, required_headers: Sequence[str] = ()) -> List[Dict[str, str]]:
    cleaned = str(text or "").lstrip("\ufeff\r\n\t ")
    if not cleaned:
        raise RuntimeError(f"{source_name}: CSV 응답이 비어 있습니다.")
    if re.match(r"(?is)^<(?:!doctype\s+html|html|head|body)\b", cleaned):
        raise RuntimeError(f"{source_name}: CSV 대신 HTML이 반환되었습니다.")

    reader = csv.DictReader(io.StringIO(cleaned, newline=""))
    if not reader.fieldnames:
        raise RuntimeError(f"{source_name}: CSV 헤더를 찾을 수 없습니다.")
    headers = [str(value or "").strip().lstrip("\ufeff") for value in reader.fieldnames]
    missing = [name for name in required_headers if name not in headers]
    if missing:
        raise RuntimeError(f"{source_name}: 필수 열 누락: {', '.join(missing)}")

    rows: List[Dict[str, str]] = []
    for row_number, row in enumerate(reader, start=2):
        normalized = {str(key or "").strip(): str(value or "").strip() for key, value in row.items() if key is not None}
        if None in row:
            raise RuntimeError(f"{source_name}: {row_number}행의 열 개수가 헤더와 다릅니다.")
        if any(normalized.values()):
            rows.append(normalized)
    return rows


def read_csv_from_url(url: str, source_name: str, required_headers: Sequence[str] = ()) -> List[Dict[str, str]]:
    url = str(url or "").strip()
    if not url:
        raise RuntimeError(f"{source_name}: CSV URL이 비어 있습니다.")
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc:
        raise RuntimeError(f"{source_name}: HTTPS URL만 허용됩니다.")

    text = download_csv_text(url, source_name)
    return parse_csv_text(text, source_name, required_headers)


def download_csv_text(url: str, source_name: str) -> str:
    url = str(url or "").strip()
    if not url:
        raise RuntimeError(f"{source_name}: CSV URL이 비어 있습니다.")
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc:
        raise RuntimeError(f"{source_name}: HTTPS URL만 허용됩니다.")
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "text/csv,text/plain,*/*"})
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            raw = response.read()
    except Exception as exc:
        raise RuntimeError(f"{source_name}: CSV 다운로드 실패 ({type(exc).__name__}).") from exc
    if not raw:
        raise RuntimeError(f"{source_name}: 다운로드 결과가 비어 있습니다.")
    try:
        return raw.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise RuntimeError(f"{source_name}: UTF-8 인코딩이 아닙니다.") from exc



def _clean_songbook_cell(value: Any) -> str:
    text = str(value or "").strip()
    if text in {"", '""', "''"}:
        return ""
    # Sheets에 문자열 그대로 기록된 연속 따옴표/공백도 빈 값으로 처리합니다.
    if re.fullmatch(r"[\"']{2,}", text):
        return ""
    return text


def parse_songbook_column_g(csv_text: str) -> List[Dict[str, str]]:
    """songbook 시트의 G열 원시 문자열을 제목/아티스트/국가/분류로 나눕니다.

    기본 입력은 헤더가 있는 전체 시트 CSV입니다. G열만 별도로 내보낸 1열 CSV도 지원합니다.
    """
    cleaned = str(csv_text or "").lstrip("\ufeff\r\n\t ")
    if not cleaned:
        return []
    if re.match(r"(?is)^<(?:!doctype\s+html|html|head|body)\b", cleaned):
        raise RuntimeError("노래책 CSV: CSV 대신 HTML이 반환되었습니다.")

    try:
        rows = list(csv.reader(io.StringIO(cleaned, newline="")))
    except csv.Error as exc:
        raise RuntimeError("노래책 CSV: CSV 해석에 실패했습니다.") from exc
    if not rows:
        return []

    # 통상 첫 행은 시트 헤더입니다. 첫 셀에 구분자 데이터가 있으면 헤더 없는 CSV로 간주합니다.
    first_row_value = rows[0][6] if len(rows[0]) > 6 else rows[0][0] if len(rows[0]) == 1 else ""
    start_index = 0 if "／" in _clean_songbook_cell(first_row_value) else 1
    result: List[Dict[str, str]] = []
    seen_raw = set()
    for row_number, row in enumerate(rows[start_index:], start=start_index + 1):
        if not row:
            continue
        raw = row[6] if len(row) > 6 else row[0] if len(row) == 1 else ""
        raw = _clean_songbook_cell(raw)
        if not raw or "／" not in raw:
            continue

        parts = [part.strip() for part in raw.split("／", 3)]
        title = _clean_songbook_cell(parts[0]) if parts else ""
        artist = _clean_songbook_cell(parts[1]) if len(parts) > 1 else ""
        country = _clean_songbook_cell(parts[2]) if len(parts) > 2 else ""
        category = _clean_songbook_cell(parts[3]) if len(parts) > 3 else ""
        if not title:
            continue

        identity = (_song_title_key(title), _normalized_identity_text(artist))
        if identity in seen_raw:
            continue
        seen_raw.add(identity)
        result.append({
            "title": title,
            "artist": artist,
            "country": country,
            "category": category,
            "source_row": str(row_number),
        })
    return result


def _normalized_identity_text(value: Any) -> str:
    text = unicodedata.normalize("NFKC", str(value or "")).casefold()
    return re.sub(r"\s+", "", text).strip()


def _song_title_key(value: Any) -> str:
    text = str(value or "").split("ㅨ", 1)[0]
    text = text.replace(" [뜌땨]", "").replace(" 🐤", "")
    text = text.replace(" [불법레이]", "").replace(" 🍥", "")
    return _normalized_identity_text(text)


def _split_multi_identity(value: Any) -> List[str]:
    parts = [part.strip() for part in str(value or "").split(" & ") if part.strip()]
    return parts or ([str(value).strip()] if str(value or "").strip() else [""])


def filter_unique_songbook_rows(songbook_rows: List[Dict[str, str]], songs: List[Dict[str, str]]) -> List[Dict[str, str]]:
    """방송 기록 곡에 제목/아티스트가 이미 존재하면 노래책 항목을 제외합니다."""
    known_pairs = set()
    known_titles = set()
    for song in songs:
        titles = [_song_title_key(value) for value in _split_multi_identity(song.get("title", ""))]
        artists = [_normalized_identity_text(value) for value in _split_multi_identity(song.get("artist", ""))]
        titles = [value for value in titles if value]
        for title in titles:
            known_titles.add(title)
            for artist in artists:
                known_pairs.add((title, artist))

    result: List[Dict[str, str]] = []
    seen_pairs = set()
    for item in songbook_rows:
        title = str(item.get("title", "")).strip()
        artist = str(item.get("artist", "")).strip()
        title_key = _song_title_key(title)
        artist_key = _normalized_identity_text(artist)
        if not title_key:
            continue
        identity = (title_key, artist_key)
        if identity in seen_pairs:
            continue
        seen_pairs.add(identity)
        if artist_key and identity in known_pairs:
            continue
        if not artist_key and title_key in known_titles:
            continue
        result.append({
            "title": title,
            "artist": artist,
            "country": str(item.get("country", "")).strip(),
            "category": str(item.get("category", "")).strip(),
        })
    return result

def to_int(value: Any) -> int:
    try:
        if value is None or value == "":
            return 0
        return int(float(str(value).replace(",", "")))
    except (TypeError, ValueError, OverflowError):
        return 0


def timeline_to_seconds(value: Any) -> int:
    text = str(value or "").strip()
    if not text:
        return 0
    if text.startswith("#t="):
        text = text[3:]
    elif text.startswith("t="):
        text = text[2:]
    try:
        parts = [int(float(part.strip())) for part in text.split(":") if part.strip()]
        if 1 <= len(parts) <= 3:
            while len(parts) < 3:
                parts.insert(0, 0)
            hours, minutes, seconds = parts[-3], parts[-2], parts[-1]
            return max(0, hours * 3600 + minutes * 60 + seconds)
    except (TypeError, ValueError, OverflowError):
        pass
    total = 0
    matched = False
    for match in re.finditer(r"(\d+(?:\.\d+)?)([hms])", text.lower()):
        matched = True
        number = float(match.group(1))
        unit = match.group(2)
        total += int(number * (3600 if unit == "h" else 60 if unit == "m" else 1))
    if matched:
        return max(0, total)
    try:
        return max(0, int(float(text)))
    except (TypeError, ValueError, OverflowError):
        return 0


def normalize_end_value(timeline: Any, end: Any) -> str:
    start_text = str(timeline or "").strip()
    end_text = str(end or "").strip()
    if not start_text or not end_text:
        return end_text
    return end_text if timeline_to_seconds(end_text) > timeline_to_seconds(start_text) else ""


def validate_song_rows(rows: List[Dict[str, str]]) -> None:
    if not rows:
        raise RuntimeError("곡 CSV에 데이터 행이 없습니다. 기존 data.json을 보존합니다.")
    seen = set()
    for index, row in enumerate(rows, start=2):
        song_id = str(row.get("id", "")).strip()
        if not song_id:
            raise RuntimeError(f"곡 CSV {index}행: id가 비어 있습니다.")
        if song_id in seen:
            raise RuntimeError(f"곡 CSV: 중복 id가 발견되었습니다 ({song_id}).")
        seen.add(song_id)
    if not any(str(row.get("title", "")).strip() for row in rows):
        raise RuntimeError("곡 CSV의 title 값이 전부 비어 있습니다.")


def parse_aliases_cell(value: Any) -> List[str]:
    text = str(value or "").strip()
    if not text:
        return []
    try:
        values = next(csv.reader([text], skipinitialspace=True))
    except (csv.Error, StopIteration):
        values = text.split(",")
    return list(dict.fromkeys(part.strip().strip('"').strip() for part in values if part.strip().strip('"').strip()))


def build_search_aliases(rows: List[Dict[str, str]]) -> Dict[str, Dict[str, Any]]:
    aliases: Dict[str, Dict[str, Any]] = {}
    for row in rows:
        word = str(row.get("word", "")).strip()
        if not word:
            continue
        aliases[word] = {
            "aliases": parse_aliases_cell(row.get("aliases")),
            "exact": str(row.get("exact", row.get("exact_match", row.get("unanimous", row.get("perfect", ""))))).strip().lower() == "true",
        }
    return aliases


def first_notice_value(rows: List[Dict[str, str]], key_name: str) -> str:
    target = key_name.strip().lower()
    for row in rows:
        if str(row.get("key", "")).strip().lower() == target and str(row.get("value", "")).strip():
            return str(row.get("value", "")).strip()
    return ""


def first_notice_row(rows: List[Dict[str, str]], key_name: str) -> Dict[str, str] | None:
    target = key_name.strip().lower()
    for row in rows:
        if str(row.get("key", "")).strip().lower() == target and str(row.get("value", "")).strip():
            return row
    return None


def build_payload(songs: List[Dict[str, str]], likes: List[Dict[str, str]], notice_rows: List[Dict[str, str]], settings_rows: List[Dict[str, str]], alias_rows: List[Dict[str, str]], songbook_rows: List[Dict[str, str]] | None = None) -> Dict[str, Any]:
    validate_song_rows(songs)
    likes_map: Dict[str, Dict[str, str]] = {}
    for row in likes:
        song_id = str(row.get("id", "")).strip()
        if song_id:
            likes_map[song_id] = row

    data = []
    for row in songs:
        song_id = str(row.get("id", "")).strip()
        like = likes_map.get(song_id, {})
        data.append({
            "id": song_id,
            "year": to_int(row.get("year")),
            "month": to_int(row.get("month")),
            "day": to_int(row.get("day")),
            "day_p": row.get("day_p", ""),
            "artist": row.get("artist", ""),
            "title": row.get("title", ""),
            "category": row.get("category", ""),
            "country": row.get("country", ""),
            "timeline": row.get("timeline", ""),
            "link": row.get("link", ""),
            "end": normalize_end_value(row.get("timeline", ""), row.get("end", "")),
            "sub1": row.get("sub1", ""),
            "sub2": row.get("sub2", ""),
            "sub3": row.get("sub3", ""),
            "likes_total": to_int(like.get("likes_total")),
            "updated_at": like.get("updated_at", ""),
            "likes_last_1d": to_int(like.get("likes_last_1d")),
            "likes_last_7d": to_int(like.get("likes_last_7d")),
            "likes_last_30d": to_int(like.get("likes_last_30d")),
        })

    cleaned_songbook = filter_unique_songbook_rows(songbook_rows or [], songs)

    h1_row = first_notice_row(notice_rows, "h1")
    h1_visible = str((h1_row or {}).get("link", "")).strip().upper() == "TRUE"
    notices = [{"text": str(row.get("value", "")).strip(), "link": str(row.get("link", "")).strip()}
               for row in notice_rows if str(row.get("key", "")).strip().lower() == "notice" and str(row.get("value", "")).strip()]
    cover_rows = [row for row in notice_rows if str(row.get("key", "")).strip().lower() == "cover" and str(row.get("value", "")).strip()]
    covers = [{"id": f"COVER_{index:05d}", "url": str(row.get("value", "")).strip(),
               "section": "오리지널 곡" if str(row.get("link", "")).strip().upper() == "TRUE" else "커버곡",
               "thumbnail": str(row.get("img", "")).strip()} for index, row in enumerate(cover_rows, start=1)]
    recs = [{"value": str(row.get("value", "")).strip(), "title": str(row.get("link", "")).strip(), "thumbnail": str(row.get("img", "")).strip()}
            for row in notice_rows if str(row.get("key", "")).strip().lower() == "rec" and str(row.get("value", "")).strip()]
    channels = [{"url": str(row.get("value", "")).strip(), "title": str(row.get("link", "")).strip(),
                 "hasCustomTitle": bool(str(row.get("link", "")).strip()), "thumbnail": str(row.get("img", "")).strip(),
                 "hasCustomThumbnail": bool(str(row.get("img", "")).strip())}
                for row in notice_rows if str(row.get("key", "")).strip().lower() == "cha" and str(row.get("value", "")).strip()]
    settings = {str(row.get("key", "")).strip(): str(row.get("value", "")).strip()
                for row in settings_rows if str(row.get("key", "")).strip()}

    return {
        "generated_at": datetime.now(KST).isoformat(timespec="seconds"),
        "data": data,
        "songbook": cleaned_songbook,
        "notices": notices,
        "covers": covers,
        "recs": recs,
        "channels": channels,
        "footerText": first_notice_value(notice_rows, "footer"),
        "title": first_notice_value(notice_rows, "title"),
        "h1": first_notice_value(notice_rows, "h1"),
        "h1Visible": h1_visible,
        "settings": settings,
        "searchAliases": build_search_aliases(alias_rows),
    }


def atomic_write_json(payload: Dict[str, Any]) -> None:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    temp_path = OUT_PATH.with_name(OUT_PATH.name + ".tmp")
    serialized = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    # 쓰기 후 다시 파싱해 결과를 검증하고, 검증된 경우에만 기존 파일을 교체합니다.
    temp_path.write_text(serialized, encoding="utf-8")
    with temp_path.open("r", encoding="utf-8") as file:
        verified = json.load(file)
    if not isinstance(verified, dict) or not isinstance(verified.get("data"), list) or not verified["data"]:
        temp_path.unlink(missing_ok=True)
        raise RuntimeError("생성된 JSON 검증에 실패했습니다. 기존 data.json을 보존합니다.")
    temp_path.replace(OUT_PATH)


def get_site_base_url() -> str:
    """index.html canonical URL에서 사이트 기본 주소를 읽습니다."""
    try:
        text = (ROOT / "public" / "index.html").read_text(encoding="utf-8")
    except OSError:
        return "https://ureisong.github.io/"
    match = re.search(r'<link\b[^>]*rel=["\']canonical["\'][^>]*href=["\']([^"\']+)', text, re.IGNORECASE)
    candidate = str(match.group(1) if match else "https://ureisong.github.io/").strip()
    parsed = urlparse(candidate)
    if parsed.scheme != "https" or not parsed.netloc:
        return "https://ureisong.github.io/"
    return candidate if candidate.endswith("/") else candidate.rsplit("/", 1)[0] + "/"


def share_page_filename(song_id: Any) -> str:
    """브라우저 encodeURIComponent와 일치하는 URL-safe 정적 공유 페이지 파일명입니다."""
    return quote(str(song_id or "").strip(), safe="-_.~") + ".html"


def format_share_display_title(value: Any) -> str:
    """app.js의 화면용 제목 치환을 정적 공유 메타데이터에도 적용합니다."""
    parts = [part.strip() for part in str(value or "").split(" & ") if part.strip()]
    if not parts:
        return "곡명 없음"
    output = []
    for part in parts:
        shown = str(part).replace("ㅨ", "")
        shown = shown.replace(" [뜌땨]", " 🐤").replace(" [불법레이]", " 🍥")
        shown = re.sub(r"\s{2,}", " ", shown).strip()
        if shown and shown not in output:
            output.append(shown)
    return " ".join(output) or "곡명 없음"


