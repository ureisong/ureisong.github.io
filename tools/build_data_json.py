def write_song_share_pages(songs: List[Dict[str, Any]], output_dir: Path | None = None, *, site_base_url: str | None = None) -> int:
    destination = output_dir or SHARE_PAGES_DIR
    destination.mkdir(parents=True, exist_ok=True)
    expected: set[str] = set()
    generated = 0
    for song in songs:
        song_id = str(song.get("id", "")).strip()
        if not song_id:
            continue
        filename = share_page_filename(song_id)
        if filename in expected:
            raise RuntimeError(f"공유 페이지 파일명 충돌: {filename}")
        expected.add(filename)
        content = render_song_share_page(song, site_base_url=site_base_url)
        target = destination / filename
        temp = target.with_name(target.name + ".tmp")
        temp.write_text(content, encoding="utf-8")
        temp.replace(target)
        generated += 1

    for existing in destination.glob("*.html"):
        if existing.name in expected:
            continue
        try:
            text = existing.read_text(encoding="utf-8")
        except OSError:
            continue
        if SHARE_PAGE_MARKER in text:
            existing.unlink(missing_ok=True)
    for temp in destination.glob("*.html.tmp"):
        temp.unlink(missing_ok=True)
    return generated

def main() -> int:
    songs_url = get_config_url("SONGS_CSV_URL")
    likes_url = get_config_url("LIKES_SMR_CSV_URL")
    notice_url = get_config_url("NOTICE_CSV_URL")
    settings_url = get_config_url("SETTINGS_CSV_URL")
    aliases_url = get_config_url("SEARCH_ALIASES_CSV_URL")
    songbook_url = get_config_url("SONGBOOK_CSV_URL")

    songs = read_csv_from_url(songs_url, "곡 CSV", (
        "id", "year", "month", "day", "day_p", "artist", "title", "category",
        "country", "timeline", "link", "end", "sub1", "sub2", "sub3"
    ))
    likes = read_csv_from_url(likes_url, "추천 집계 CSV", (
        "id", "likes_total", "updated_at", "likes_last_1d", "likes_last_7d", "likes_last_30d"
    ))
    if not likes:
        raise RuntimeError("추천 집계 CSV에 데이터 행이 없습니다. 기존 data.json을 보존합니다.")
    notice_rows = read_csv_from_url(notice_url, "공지 CSV", ("key", "value")) if notice_url else []
    settings_rows = read_csv_from_url(settings_url, "설정 CSV", ("key", "value")) if settings_url else []
    alias_rows = read_csv_from_url(aliases_url, "검색 별칭 CSV", ("word", "aliases")) if aliases_url else []
    if songbook_url:
        songbook_rows = parse_songbook_column_g(download_csv_text(songbook_url, "노래책 CSV"))
    else:
        songbook_rows = []
        print("NOTICE: SONGBOOK_CSV_URL 미설정 — data.json의 songbook은 빈 목록으로 생성됩니다.")

    payload = build_payload(songs, likes, notice_rows, settings_rows, alias_rows, songbook_rows)
    atomic_write_json(payload)
    share_pages_count = write_song_share_pages(payload["data"])
    size_kb = OUT_PATH.stat().st_size / 1024
    print(f"Wrote {OUT_PATH} ({len(payload['data'])} songs, {len(payload['songbook'])} songbook-only songs, {size_kb:.1f} KiB)")
    print(f"Generated {share_pages_count} song share pages in {SHARE_PAGES_DIR}")
    return 0

